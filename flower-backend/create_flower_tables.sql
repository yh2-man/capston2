-- ── 포괄 카테고리 ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS flower_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,   -- 벚꽃, 장미, 진달래 등
    emoji       VARCHAR(10),
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

