-- ── 꽃 도감 ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS flowers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_no          VARCHAR(20) UNIQUE,          -- 농사로 고유번호
    name             VARCHAR(100) NOT NULL,        -- 꽃 이름
    scientific_name  VARCHAR(200),                 -- 학명 (Plant.id 매핑 핵심)
    bloom_month      INT,                          -- 개화월
    bloom_day        INT,                          -- 개화일
    flower_language  TEXT,                         -- 꽃말
    description      TEXT,                         -- 꽃 설명
    grow_tips        TEXT,                         -- 키우는 법
    image_url        VARCHAR(1024),                -- 이미지 URL
    category_id      BIGINT REFERENCES flower_categories(id),
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_flowers_name          ON flowers(name);
CREATE INDEX IF NOT EXISTS idx_flowers_scientific    ON flowers(scientific_name);
CREATE INDEX IF NOT EXISTS idx_flowers_category      ON flowers(category_id);
CREATE INDEX IF NOT EXISTS idx_flowers_bloom_month   ON flowers(bloom_month);

-- ── AI 학명 → 카테고리 매핑 ──────────────────────────────────
-- Plant.id가 반환한 학명을 카테고리로 연결하는 테이블
-- 3단계 매칭: 완전일치 → 속명(genus) → 여기서 수동 매핑
CREATE TABLE IF NOT EXISTS flower_species_mapping (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_name      VARCHAR(200) NOT NULL UNIQUE,  -- Plant.id 반환 학명 or 일반명
    category_id  BIGINT REFERENCES flower_categories(id),
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_species_mapping_name ON flower_species_mapping(ai_name);

